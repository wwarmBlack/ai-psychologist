def build_client_profile(profile: dict, answers: dict) -> str:
    """Собирает текстовый блок о клиенте для системного промпта."""
    lines = []
    if profile.get("name"):
        lines.append(f"Имя: {profile['name']}")
    if profile.get("age"):
        lines.append(f"Возраст: {profile['age']}")
    if profile.get("about"):
        lines.append(f"О себе: {profile['about']}")
    q_by_id = {q["id"]: q["question"] for q in ONBOARDING_QUESTIONS}
    for qid, answer in (answers or {}).items():
        if qid in q_by_id and answer:
            lines.append(f"{q_by_id[qid]} — {answer}")
    return "\n".join(lines) if lines else "Клиент пока не заполнил профиль."


def build_session_prompt(psychologist: dict, profile: dict, answers: dict) -> str:
    return BASE_SYSTEM_PROMPT.format(
        persona=psychologist["persona"],
        client_profile=build_client_profile(profile, answers),
    )
